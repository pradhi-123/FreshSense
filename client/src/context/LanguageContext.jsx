const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [langCode, setLangCode] = useState(() => {
    return localStorage.getItem('virasat_lang') || 'en';
  });

  useEffect(() => {
    localStorage.setItem('virasat_lang', langCode);
  }, [langCode]);

  const t = (key) => {
    const langObj = translations[langCode] || translations.en;
    return langObj[key] || translations.en[key] || key;
  };

  const currentLangObj = bhashiniLanguages.find((l) => l.code === langCode) || bhashiniLanguages[0];

  return (
    <LanguageContext.Provider value={{ langCode, setLangCode, t, currentLangObj, bhashiniLanguages }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
